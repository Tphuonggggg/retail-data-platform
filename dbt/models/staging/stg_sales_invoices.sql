select _run_id as _capture_id, _row_ordinal as _raw_row_ordinal,
  'Sales.Invoices'::text as source_object,
  "InvoiceID"::text as source_business_key,
  md5(_run_id::text || ':Sales.Invoices:' || _row_ordinal::text) as record_identity,
  {{ ruleset() }} as ruleset_version,
  {{ evaluation_id() }} as evaluation_id,
  cast("InvoiceID" as integer) as invoice_id,
  cast("CustomerID" as integer) as customer_id,
  cast("BillToCustomerID" as integer) as bill_to_customer_id,
  cast("OrderID" as integer) as order_id,
  cast("DeliveryMethodID" as integer) as delivery_method_id,
  cast("ContactPersonID" as integer) as contact_person_id,
  cast("AccountsPersonID" as integer) as accounts_person_id,
  cast("SalespersonPersonID" as integer) as salesperson_person_id,
  cast("PackedByPersonID" as integer) as packed_by_person_id,
  cast("InvoiceDate" as date) as invoice_date,
  cast("CustomerPurchaseOrderNumber" as text) as customer_purchase_order_number,
  cast("IsCreditNote" as boolean) as is_credit_note,
  cast("CreditNoteReason" as text) as credit_note_reason,
  cast("Comments" as text) as comments,
  cast("DeliveryInstructions" as text) as delivery_instructions,
  cast("InternalComments" as text) as internal_comments,
  cast("TotalDryItems" as integer) as total_dry_items,
  cast("TotalChillerItems" as integer) as total_chiller_items,
  cast("DeliveryRun" as text) as delivery_run,
  cast("RunPosition" as text) as run_position,
  cast("ReturnedDeliveryData" as text) as returned_delivery_data,
  cast("ConfirmedDeliveryTime" as text) collate "C" as confirmed_delivery_time,
  cast("ConfirmedReceivedBy" as text) as confirmed_received_by,
  cast("LastEditedBy" as integer) as last_edited_by,
  cast("LastEditedWhen" as text) collate "C" as last_edited_when
from {{ sales_raw_input('sales_invoices') }}
where _run_id = {{ capture_id() }}
